// Writes docs/translations/template.js: every string the cards show, in
// English, as a ready translation file for the "Your own translations"
// mechanism. Run by `npm run docs`, so CI notices when it falls behind.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const result = await build({
  entryPoints: ["src/localize.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  write: false,
  logLevel: "error",
  footer: { js: "export const __defaultTranslations = defaultTranslations;" },
});
const url = `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`;
const { __defaultTranslations } = await import(url);
const en = __defaultTranslations.en;
const keys = Object.keys(en);

const out = `// M3 Cards — translation template. Generated by \`npm run docs\`; edit a copy, not this file.
//
// Every text the cards show, in English (${keys.length} of them).
//
// To translate:
// 1. Save a copy as config/www/m3-cards-<language>.js and change "xx" below to
//    your language's code as Home Assistant uses it ("pl", "fr", "pt-BR", …).
// 2. Replace each English text in quotes with yours. Keep the key on the left,
//    and keep anything in {curly braces} exactly as it is: the card puts a
//    number or a name there. Lines you leave out or leave in English stay
//    English, so a partial translation works.
// 3. Add it under Settings → Dashboards → ⋮ → Resources as
//    /local/m3-cards-<language>.js (JavaScript module) and reload the page.
//
// To have it built into the cards, attach the file (zipped) to an issue or
// open a pull request.

window.m3CardsTranslations = {
  ...window.m3CardsTranslations,
  xx: {
${keys.map((k) => `    ${k}: ${JSON.stringify(en[k])},`).join("\n")}
  },
};
window.dispatchEvent(new Event("m3-cards-translations-loaded"));
`;
writeFileSync("docs/translations/template.js", out);
